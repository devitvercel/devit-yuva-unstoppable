import fs from 'fs';
import path from 'path';

const logosDir = path.resolve('public/assets/company-logos-updated');
const files = fs.readdirSync(logosDir)
  .filter(file => file.endsWith('.svg'))
  .sort((a, b) => {
    // Sort custom names last
    const aIsImg = a.startsWith('image ');
    const bIsImg = b.startsWith('image ');
    if (aIsImg && !bIsImg) return -1;
    if (!aIsImg && bIsImg) return 1;
    if (aIsImg && bIsImg) {
      const aNum = parseInt(a.replace('image ', ''));
      const bNum = parseInt(b.replace('image ', ''));
      return aNum - bNum;
    }
    return a.localeCompare(b);
  });

console.log(`Found ${files.length} logos.`);

const fileContent = `// Automatically generated by scratch/generate_logo_list.mjs
export const companyLogos = ${JSON.stringify(files, null, 2)};
`;

const outputPath = path.resolve('src/data/home/companyLogos.ts');
fs.writeFileSync(outputPath, fileContent, 'utf-8');
console.log(`Successfully generated ${outputPath}`);
